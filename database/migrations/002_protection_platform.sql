-- ScamShield protection platform: unified history, report tracking, notifications,
-- learning progress, preferences, sessions, two-factor auth and audit events.

-- Profiles: two-factor authentication and academy announcement tracking.
alter table public.profiles add column if not exists totp_secret text;
alter table public.profiles add column if not exists totp_enabled boolean not null default false;
alter table public.profiles add column if not exists totp_last_step bigint;
alter table public.profiles add column if not exists academy_notified_version integer not null default 0;
alter table public.profiles add column if not exists updated_at timestamptz not null default now();

-- Sign-in sessions, so users can review and revoke them.
create table if not exists public.user_sessions (
  id uuid primary key,
  user_id bigint not null references public.profiles(id) on delete cascade,
  user_agent text not null default '',
  created_at timestamptz not null default now(),
  last_seen_at timestamptz not null default now(),
  revoked_at timestamptz
);
create index if not exists user_sessions_user_idx on public.user_sessions (user_id, created_at desc);

-- Scam history: messages, URL scans and sender checks share one table.
alter table public.scam_cases add column if not exists kind text not null default 'message';
alter table public.scam_cases add column if not exists details jsonb not null default '{}'::jsonb;
alter table public.scam_cases drop constraint if exists scam_cases_kind_check;
alter table public.scam_cases add constraint scam_cases_kind_check check (kind in ('message', 'url', 'sender'));
create index if not exists scam_cases_user_kind_idx on public.scam_cases (user_id, kind, created_at desc);
create index if not exists scam_cases_user_risk_idx on public.scam_cases (user_id, risk_level);

-- Scam reports: richer details and the new status workflow.
alter table public.scam_reports drop constraint if exists scam_reports_status_check;
update public.scam_reports set status = case status
  when 'open' then 'submitted'
  when 'reviewing' then 'under_review'
  when 'confirmed' then 'verified'
  when 'false_positive' then 'rejected'
  when 'closed' then 'resolved'
  else status end;
alter table public.scam_reports alter column status set default 'submitted';
alter table public.scam_reports add constraint scam_reports_status_check
  check (status in ('submitted', 'under_review', 'verified', 'rejected', 'resolved'));
alter table public.scam_reports drop constraint if exists scam_reports_details_check;
alter table public.scam_reports add constraint scam_reports_details_check check (char_length(details) between 1 and 2000);
alter table public.scam_reports add column if not exists message_text text check (char_length(message_text) <= 5000);
alter table public.scam_reports add column if not exists url text check (char_length(url) <= 2048);
alter table public.scam_reports add column if not exists sender_type text check (sender_type in ('phone', 'email', 'name'));
alter table public.scam_reports add column if not exists sender_value text check (char_length(sender_value) <= 200);
alter table public.scam_reports add column if not exists sender_normalized text;
alter table public.scam_reports add column if not exists admin_feedback text check (char_length(admin_feedback) <= 2000);
alter table public.scam_reports add column if not exists updated_at timestamptz not null default now();
create index if not exists scam_reports_sender_idx on public.scam_reports (sender_type, sender_normalized);

-- Report timeline: status changes, admin feedback and extra information from the reporter.
create table if not exists public.report_updates (
  id bigint generated by default as identity primary key,
  report_id bigint not null references public.scam_reports(id) on delete cascade,
  author_id bigint references public.profiles(id) on delete set null,
  kind text not null check (kind in ('created', 'status', 'feedback', 'user_note')),
  from_status text,
  to_status text,
  note text check (char_length(note) <= 2000),
  created_at timestamptz not null default now()
);
create index if not exists report_updates_report_idx on public.report_updates (report_id, created_at);

-- Evidence files are stored in the database and only served through authorized endpoints.
create table if not exists public.report_evidence (
  id bigint generated by default as identity primary key,
  report_id bigint not null references public.scam_reports(id) on delete cascade,
  uploader_id bigint references public.profiles(id) on delete set null,
  file_name text not null check (char_length(file_name) <= 200),
  mime_type text not null check (mime_type in ('image/png', 'image/jpeg', 'application/pdf', 'text/plain')),
  size_bytes integer not null check (size_bytes between 1 and 2097152),
  sha256 text not null,
  data bytea not null,
  created_at timestamptz not null default now()
);
create index if not exists report_evidence_report_idx on public.report_evidence (report_id);

-- In-app notifications.
create table if not exists public.notifications (
  id bigint generated by default as identity primary key,
  user_id bigint not null references public.profiles(id) on delete cascade,
  type text not null check (type in ('analysis', 'report_status', 'education', 'threat_alert', 'security')),
  title text not null check (char_length(title) <= 200),
  body text not null default '' check (char_length(body) <= 2000),
  link text check (char_length(link) <= 300),
  read_at timestamptz,
  created_at timestamptz not null default now()
);
create index if not exists notifications_user_idx on public.notifications (user_id, created_at desc);
create index if not exists notifications_unread_idx on public.notifications (user_id) where read_at is null;

create table if not exists public.user_preferences (
  user_id bigint primary key references public.profiles(id) on delete cascade,
  notify_analysis boolean not null default false,
  notify_report_status boolean not null default true,
  notify_education boolean not null default true,
  notify_threat_alerts boolean not null default true,
  notify_security boolean not null default true,
  updated_at timestamptz not null default now()
);

-- Scam Awareness Academy progress. Module content lives in lib/academy.js.
create table if not exists public.learning_progress (
  user_id bigint not null references public.profiles(id) on delete cascade,
  module_id text not null check (char_length(module_id) <= 60),
  lesson_completed_at timestamptz,
  quiz_score integer,
  quiz_total integer,
  best_score integer,
  attempts integer not null default 0,
  completed_at timestamptz,
  updated_at timestamptz not null default now(),
  primary key (user_id, module_id)
);

-- Scam pattern alerts published by administrators.
create table if not exists public.scam_alerts (
  id bigint generated by default as identity primary key,
  author_id bigint references public.profiles(id) on delete set null,
  report_id bigint references public.scam_reports(id) on delete set null,
  title text not null check (char_length(title) between 3 and 200),
  body text not null check (char_length(body) between 3 and 2000),
  category text not null check (char_length(category) <= 120),
  created_at timestamptz not null default now()
);

-- Security-relevant events. Never store passwords, codes or message contents here.
create table if not exists public.audit_events (
  id bigint generated by default as identity primary key,
  user_id bigint references public.profiles(id) on delete set null,
  actor_id bigint references public.profiles(id) on delete set null,
  event text not null check (char_length(event) <= 80),
  details jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);
create index if not exists audit_events_user_idx on public.audit_events (user_id, created_at desc);
