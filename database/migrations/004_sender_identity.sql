-- Sender identity: an admin-curated directory of official business contacts, a cache for paid
-- carrier lookups, and the full international number on reports so matches don't cross countries.

-- Official phone numbers and email addresses, each confirmed by an administrator from a source
-- the business controls (its website, app, statement or card). Only these produce "Verified Business".
create table if not exists public.verified_senders (
  id bigint generated by default as identity primary key,
  sender_type text not null check (sender_type in ('phone', 'email')),
  -- E.164 for phones (+255754123456), lower-case address for emails.
  match_key text not null check (char_length(match_key) between 3 and 200),
  display_value text not null check (char_length(display_value) <= 200),
  business_name text not null check (char_length(business_name) between 2 and 120),
  source text not null check (char_length(source) between 3 and 300),
  added_by bigint references public.profiles(id) on delete set null,
  created_at timestamptz not null default now(),
  unique (sender_type, match_key)
);

-- Carrier lookups (e.g. Twilio Lookup) are billed per request, so results are cached by number.
-- Only network details and registered business names are stored, never a private person's name.
create table if not exists public.phone_lookup_cache (
  e164 text primary key check (e164 ~ '^\+[1-9][0-9]{6,14}$'),
  provider text not null,
  data jsonb not null,
  fetched_at timestamptz not null default now()
);

alter table public.scam_reports add column if not exists sender_e164 text check (sender_e164 ~ '^\+[1-9][0-9]{6,14}$');
