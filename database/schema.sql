create table if not exists public.profiles (
  id bigint generated by default as identity primary key,
  email text not null unique,
  display_name text not null default '',
  password_hash text not null,
  role text not null default 'user' check (role in ('user', 'admin')),
  created_at timestamptz not null default now()
);

create table if not exists public.scam_cases (
  id bigint generated by default as identity primary key,
  user_id bigint not null references public.profiles(id) on delete cascade,
  message text not null check (char_length(message) <= 5000),
  score integer not null check (score between 0 and 100),
  risk_level text not null check (risk_level in ('low', 'medium', 'high')),
  scam_type text not null,
  signals jsonb not null default '[]'::jsonb,
  url_checks jsonb not null default '[]'::jsonb,
  phone_checks jsonb not null default '[]'::jsonb,
  created_at timestamptz not null default now()
);

create table if not exists public.scam_reports (
  id bigint generated by default as identity primary key,
  user_id bigint not null references public.profiles(id) on delete cascade,
  case_id bigint references public.scam_cases(id) on delete set null,
  scam_type text not null,
  details text not null check (char_length(details) between 1 and 500),
  status text not null default 'open' check (status in ('open', 'reviewing', 'confirmed', 'false_positive', 'closed')),
  created_at timestamptz not null default now()
);

create index if not exists scam_cases_user_created_idx on public.scam_cases (user_id, created_at desc);
create index if not exists scam_reports_user_created_idx on public.scam_reports (user_id, created_at desc);
create index if not exists scam_reports_status_created_idx on public.scam_reports (status, created_at desc);